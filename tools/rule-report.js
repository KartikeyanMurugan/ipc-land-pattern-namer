// Writes docs/RULES.md: every family, its formula, source and evidence level.
// Run: node tools/rule-report.js
'use strict';
const fs = require('fs');
const path = require('path');
const rules = require('../rules/ipc-7351b.js');
const ds = require('../test/datasheet-cases.json').cases;

const lines = [];
lines.push('# Rule traceability', '');
lines.push('Generated by `node tools/rule-report.js` - do not edit by hand.', '');
lines.push('## Sources', '');
for (const [k, v] of Object.entries(rules.sources)) lines.push(`- **${k}** – ${v}`);
lines.push('', '## Value and rounding policy', '');
for (const v of Object.values(rules.policy)) lines.push(`- ${v}`);
lines.push('', '## Evidence levels', '');
lines.push('- **Datasheet verified** – a real part checked by a PCB designer (`test/datasheet-cases.json`, status `verified`)');
lines.push('- **Source example** – reproduces an example printed in the source document');
lines.push('- **Derived example** – formula from the source, example built by the project, not printed in the source');
lines.push('- **Formula only** – formula from the source, no example yet', '');
lines.push('## Families', '');
lines.push('| Family | Name | Formula | Source | Evidence |', '|---|---|---|---|---|');
let counts = {};
for (const [id, f] of Object.entries(rules.families)) {
  const ex = rules.examples.filter(e => e.family === id);
  const ver = ds.filter(c => c.family === id && c.status === 'verified');
  let ev = 'Formula only';
  if (ver.length) ev = 'Datasheet verified';
  else if (ex.some(e => e.source === 'pdf')) ev = 'Source example';
  else if (ex.length) ev = 'Derived example';
  counts[ev] = (counts[ev] || 0) + 1;
  lines.push(`| \`${id}\` | ${f.name} | \`${f.template}${f.qty ? '-<pins>' : ''}\` | ${f.source} | ${ev} |`);
}
lines.splice(lines.indexOf('## Families') + 1, 0, '', Object.entries(counts).map(([k, v]) => `${k}: **${v}**`).join(' · '));
fs.mkdirSync(path.join(__dirname, '..', 'docs'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'RULES.md'), lines.join('\n') + '\n');
console.log('wrote docs/RULES.md', counts);
